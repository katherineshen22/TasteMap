-- Recipes users write themselves or import from a link.
create table if not exists public.user_recipes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  source_url text,
  image_url text,
  photo_path text,
  cuisine text,
  total_minutes integer check (total_minutes is null or total_minutes between 0 and 10000),
  servings text,
  ingredients text[] not null default '{}',
  instructions text[] not null default '{}',
  tags text[] not null default '{}',
  notes text,
  rating numeric check (rating is null or rating between 1 and 10),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists user_recipes_user_idx
  on public.user_recipes (user_id, created_at desc);

alter table public.user_recipes enable row level security;

drop policy if exists "Users can read own recipes" on public.user_recipes;
create policy "Users can read own recipes" on public.user_recipes
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert own recipes" on public.user_recipes;
create policy "Users can insert own recipes" on public.user_recipes
  for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update own recipes" on public.user_recipes;
create policy "Users can update own recipes" on public.user_recipes
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete own recipes" on public.user_recipes;
create policy "Users can delete own recipes" on public.user_recipes
  for delete to authenticated using ((select auth.uid()) = user_id);
